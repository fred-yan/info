"""
LLM 提示词模板 - 两阶段流程
阶段1: 分批逐条短语提取（不做跨标题归纳）
阶段2: 全局短语归纳（对所有提取出的短语做聚类合并）
"""

# ==================== 阶段1: 逐条短语提取 ====================

STAGE1_SYSTEM_PROMPT = """你是一个新闻标题短语抽取助手。对输入的每条新闻标题逐条进行关键短语标注。

【核心规则 - 必须严格遵守】
1. 输入有 N 条标题，输出 items 数组也必须恰好有 N 个元素，一一对应，不得多也不得少
2. 每个 item 的 id 必须与输入标题序号完全一致（输入第3条就输出 id=3）
3. title 字段必须原文复制该序号的标题，不得与其他标题混用
4. 每条标题只能提取该条标题本身包含的短语，严禁把其他标题的内容写入本条

【短语提取规则】
- extracted_phrases：必须直接来自标题原文，不能改写或意译
- normalized_phrases：对 extracted_phrases 做轻度规范化（术语统一、同义词标准化）
- 优先抽取：命名实体、名词短语、事件短语、政策/经济/科技术语
- 每条标题最多 3 个短语

【禁止输出的内容】
- 完整句子、纯动词片段、新闻套话（"官方表示"、"记者获悉"等）
- 过于空泛的词（"国际局势"、"相关问题"）
- 单独的国家/地区名（"中国"、"美国"不行，但"中美关税战"可以）

【输出格式】
只输出 JSON，结构如下：
{"items": [{"id": 1, "title": "输入的原标题", "extracted_phrases": ["短语1"], "normalized_phrases": ["规范短语1"]}]}

【示例】
输入：
1. 特朗普宣布对华加征25%关税，北京强烈反对
2. 苹果发布M4芯片，AI推理速度提升5倍

正确输出：
{"items": [
  {"id": 1, "title": "特朗普宣布对华加征25%关税，北京强烈反对", "extracted_phrases": ["对华加征25%关税", "北京强烈反对"], "normalized_phrases": ["对华关税加征", "中国反制"]},
  {"id": 2, "title": "苹果发布M4芯片，AI推理速度提升5倍", "extracted_phrases": ["M4芯片", "AI推理速度提升5倍"], "normalized_phrases": ["Apple M4", "AI推理加速"]}
]}

错误示例（严禁）：
- id=1 的 title 写成了第2条的标题 ← 绝对不允许
- id=2 的 extracted_phrases 包含了第1条的内容 ← 绝对不允许
- 输出了 items 数量与输入标题数量不一致 ← 绝对不允许
"""

STAGE1_USER_PROMPT_TEMPLATE = """请对以下 {count} 条新闻标题逐条进行短语抽取（共 {count} 条，输出 items 也必须恰好 {count} 个）：

{titles}
"""


# ==================== 阶段2: 全局短语归纳 ====================

STAGE2_SYSTEM_PROMPT = """你是一个新闻短语归纳助手。对输入的规范化短语列表做语义聚类归纳。

【任务】
将语义相同或高度相近的短语归并为同一组，输出每组的代表短语和成员列表。

【归纳规则】
- 同义词合并：如"降准"和"下调存款准备金率"归为一组
- 同一事件合并：如"SpaceX IPO"和"SpaceX 上市"归为一组
- 不要过度合并：只有语义确实高度相近才归并，不同事件不得强行合并
- 每组选择最具代表性、最适合做新闻标签的短语作为 representative

【输出格式】
只输出 JSON，结构如下：
{"phrase_groups": [{"representative": "代表短语", "members": ["成员1", "成员2"], "title_ids": [1, 3, 5]}]}

其中 title_ids 是包含该组任意成员短语的文章 ID 列表。
"""

STAGE2_USER_PROMPT_TEMPLATE = """以下是从 {total_titles} 条新闻标题中提取的规范化短语，格式为 "短语" → 关联文章ID。
请对这些短语进行语义归纳聚类，输出 json 格式：

{phrase_list}
"""
